/// Width in em of `ch` in the standard font `base_name`, if it is one.
pub fn standard_width(base_name: &str, ch: char) -> Option<f32> {
    let lower = base_name.to_ascii_lowercase();
    let table: Option<&[u16; 95]> = if lower.contains("courier") {
        return Some(0.6);
    } else if lower.contains("helvetica") || lower.contains("arial") {
        Some(if lower.contains("bold") { &HELVETICA_BOLD } else { &HELVETICA })
    } else if lower.contains("times") {
        Some(&TIMES_ROMAN)
    } else {
        None
    };
    let table = table?;
    let code = ch as u32;
    if (0x20..=0x7E).contains(&code) {
        Some(table[(code - 0x20) as usize] as f32 / 1000.0)
    } else {
        Some(if lower.contains("times") { 0.5 } else { 0.556 })
    }
}
